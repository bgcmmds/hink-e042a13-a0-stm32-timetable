/**
  ******************************************************************************
  * @file    timetable_demo.c
  * @brief   课程表演示 / 自检入口（示例数据与演示画面）
  *
  *          本文件与 timetable.c 分开：
  *            - timetable.c  = 可复用的业务模块（布局 + 数据结构 + 绘制）
  *            - 本文件        = 演示数据与启动流程，替换成你自己的课表即可
  *
  *          改成你自己的课表：把 TT_Demo() 里的 TT_SetCourse() 换成真实数据，
  *          或在 main() 里换成「读 Flash / 收串口」后调 TT_Show()。
  ******************************************************************************
  */
#include "timetable.h"
#include "epd.h"
#include "log.h"

/* ── 演示：5天 x 5大节 框架 + 几个示例课 ────────────────────────────────────
 * 注：示例课程名用 ASCII 占位。中文课程名需要额外字库（见 README「中文字库」）。
 * -------------------------------------------------------------------------*/
void TT_Demo(void)
{
    EPD_Init();
    TT_Clear();

    /* 示例课：day 0..4 = 周一..周五；period 0..4 = 上午1/上午2/下午1/下午2/晚上 */
    TT_SetCourse(0, 0, "Math");          /* 周一 上午1 */
    TT_SetCourse(0, 1, "English");       /* 周一 上午2 */
    TT_SetCourse(1, 0, "Physics");       /* 周二 上午1 */
    TT_SetCourse(2, 2, "CAD/CAM");       /* 周三 下午1 */
    TT_SetCourse(3, 3, "MechDesign");    /* 周四 下午2 */
    TT_SetCourse(4, 4, "SelfStudy");     /* 周五 晚上 */

    LOG(">>> 课程表演示：绘制 + 刷新\r\n");
    TT_Show();                           /* 画框架 + 内容 + 刷新 + 睡眠 */
    LOG(">>> 完成\r\n");
}
