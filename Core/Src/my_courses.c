/*
 * my_courses.c —— 课程表数据（示例）
 *
 * ★ 这个文件是「数据」，不是「代码」。换成你自己的课表有两种方式：
 *
 *   方式 A（推荐）：跑网页编辑器，点几下就好
 *       python tools/server.py      → 浏览器打开 http://127.0.0.1:8000
 *       （或双击 tools/课表编辑器.bat）
 *       编辑完点「生成代码」，这个文件会被自动重写。
 *
 *   方式 B：直接改下面的 TT_AddCourse 调用（改完记得同步字库，见 README）
 *
 * ── 参数说明 ──────────────────────────────────────────────────────────
 *   TT_SetWeek(N)                     左上角显示「N周」
 *   TT_AddCourse(星期, 起始节, 持续节数, "课程名", "教室")
 *
 *   星期     0~4  = 周一 ~ 周五
 *   起始节   0~4  = 上午一 / 上午二 / 下午一 / 下午二 / 晚上
 *   持续节数 1    = 单节；2 = 连堂（气泡连成一块，中间横线消失）
 *   教室     写全名即可，屏上只显示房间号（「主楼302」→「302」）。
 *            没有数字的（「操场」）原样显示；空串显示占位符。
 *
 * ── 两个注意点 ────────────────────────────────────────────────────────
 *   1) 同一时段不能有两门课，冲突的会被 TT_AddCourse 拒绝（返回 0）。
 *   2) 课程名/教室用到的汉字必须在字库子集里，否则屏上显示成空心方框。
 *      跑一次 tools/font_export.py 就能自动补齐（见 README）。
 */
#include "my_courses.h"
#include "timetable.h"

void MyCourses_Load(void)
{
    TT_SetWeek(3);                                   /* 左上角显示「3周」 */

    /* ── 周一 ─────────────────────────────────────────── */
    TT_AddCourse(0, 0, 2, "高等数学", "主楼302");     /* 上午一~二 连堂 */
    TT_AddCourse(0, 3, 1, "大学英语", "外语201");     /* 下午二 */

    /* ── 周二 ─────────────────────────────────────────── */
    TT_AddCourse(1, 0, 2, "大学物理", "物理105");     /* 上午一~二 连堂 */
    TT_AddCourse(1, 3, 2, "体育",     "操场");        /* 下午二~晚上 连堂 */

    /* ── 周三 ─────────────────────────────────────────── */
    TT_AddCourse(2, 0, 2, "数据结构", "计算机401");   /* 上午一~二 连堂 */
    TT_AddCourse(2, 3, 1, "机械设计", "机械502");     /* 下午二 */

    /* ── 周四 ─────────────────────────────────────────── */
    TT_AddCourse(3, 2, 1, "机械制造", "");            /* 下午一（无教室）*/

    /* ── 周五 ─────────────────────────────────────────── */
    TT_AddCourse(4, 3, 2, "工程图学", "绘图室");      /* 下午二~晚上 连堂 */
}
