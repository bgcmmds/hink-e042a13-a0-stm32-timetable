/* 取字模：越界返回 NULL，调用方需判空 */
const uint8_t* FONT_GetAscii(uint8_t ch)
{
    if (ch < 0x20 || ch > 0x7E) {
        return 0;
    }
    return Font8x16[ch - 0x20];
}
