/**
  ******************************************************************************
  * @file    font.h
  * @brief   字模数据与取模接口（分类：字体模块）
  *
  *          当前包含：ASCII 8x16 点阵（可打印字符 0x20~0x7E，共 95 个）
  *
  *          点阵格式说明（很重要，接中文库时照此约定）：
  *            每字符 16 字节 = 上半 8 行(8 字节) + 下半 8 行(8 字节)
  *            每字节 = 一列中的 8 个垂直像素，**bit0 在最上，bit7 在最下**
  *            （纵向取模、低位在上；画字时逐位移入显存）
  *
  *          为什么独立成模块：后续要加中文字库/多字号，
  *          都往 font.c 里加数据、往 font.h 里加声明即可，不污染屏驱动。
  ******************************************************************************
  */
#ifndef __FONT_H
#define __FONT_H

#include <stdint.h>

/* 字号定义 ----------------------------------------------------------------*/
#define FONT_ASCII_W   8      /* 字符宽（像素，字模本身） */
#define FONT_ASCII_H   16     /* 字符高（像素） */
#define FONT_ASCII_BYTES_PER_CHAR  16   /* 每字符字节数 */

/* 字符前进步长 = 字模宽 + 字距。
 * 字距 1px：字模本身占满 8px，不留空隙会「粘在一起」（实测反馈）。
 * 排字/算每行容量时都用这个值，不要直接用 FONT_ASCII_W。 */
#define FONT_ASCII_SPACING  1
#define FONT_ASCII_ADV      (FONT_ASCII_W + FONT_ASCII_SPACING)   /* = 9 */

/* 取字模：返回指向该字符点阵数据的指针；不支持的字符返回 NULL。
 * 字符集：0x20(空格) ~ 0x7E(~)，共 95 个可打印 ASCII。 */
const uint8_t* FONT_GetAscii(uint8_t ch);

#endif /* __FONT_H */
